"""
Turns a short WAV (mono, 16-bit) into a C header the worker strap can play through
its speaker (firmware/worker_strap/voice_are_you_ok.h).

Make the WAV with Windows' built-in speech (8 kHz, 16-bit, mono), e.g. in PowerShell:
    Add-Type -AssemblyName System.Speech
    $s = New-Object System.Speech.Synthesis.SpeechSynthesizer
    $f = New-Object System.Speech.AudioFormat.SpeechAudioFormatInfo(8000, 'Sixteen', 'Mono')
    $s.SetOutputToWaveFile("are_you_ok.wav", $f); $s.Speak("Are you okay?"); $s.Dispose()
Then:
    .venv\\Scripts\\python.exe tools\\make_voice.py are_you_ok.wav firmware\\worker_strap\\voice_are_you_ok.h

It trims silence, normalises, boosts (with soft clipping, louder on a small speaker)
and stores 8-bit unsigned samples (128 = silence).
"""
import math
import struct
import sys
import wave

GAIN = 2.0          # >1 = louder; peaks are soft-clipped


def main(src, dst):
    with wave.open(src, "rb") as w:
        assert w.getnchannels() == 1 and w.getsampwidth() == 2, "need mono 16-bit WAV"
        rate = w.getframerate()
        raw = w.readframes(w.getnframes())
    x = [v / 32768.0 for v in struct.unpack(f"<{len(raw) // 2}h", raw)]
    # trim leading/trailing silence
    thr = 0.02
    start = next((i for i, v in enumerate(x) if abs(v) > thr), 0)
    end = len(x) - next((i for i, v in enumerate(reversed(x)) if abs(v) > thr), 0)
    x = x[max(0, start - rate // 50):min(len(x), end + rate // 50)]
    peak = max(abs(v) for v in x) or 1.0
    y = [math.tanh(GAIN * v / peak) / math.tanh(GAIN) for v in x]   # normalise + soft clip
    data = [max(0, min(255, int(round(128 + 127 * v)))) for v in y]
    lines = [", ".join(str(b) for b in data[i:i + 24]) for i in range(0, len(data), 24)]
    with open(dst, "w", encoding="utf-8") as f:
        f.write(f"// Generated by tools/make_voice.py from {src.split(chr(92))[-1].split('/')[-1]}\n")
        f.write(f"// {len(data)} samples, {rate} Hz, 8-bit unsigned (128 = silence), {len(data) / rate:.2f} s\n")
        f.write("#pragma once\n#include <stdint.h>\n")
        f.write(f"const uint32_t VOICE_RATE = {rate};\n")
        f.write(f"const uint32_t VOICE_LEN = {len(data)};\n")
        f.write("const uint8_t VOICE_DATA[] = {\n  " + ",\n  ".join(lines) + "\n};\n")
    print(f"{dst}: {len(data)} samples = {len(data) / rate:.2f} s at {rate} Hz")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
